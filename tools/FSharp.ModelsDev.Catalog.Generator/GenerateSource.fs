/// Deterministic F# source generation for the compiled-in catalog indexes.
module FSharp.ModelsDev.Catalog.Generator.GenerateSource

open System.Text

let private escapeString (s: string) : string =
    let sb = StringBuilder()

    for c in s do
        match c with
        | '\\' -> sb.Append("\\\\") |> ignore
        | '"' -> sb.Append("\\\"") |> ignore
        | c when c < ' ' -> sb.Append(sprintf "\\u%04x" (int c)) |> ignore
        | c -> sb.Append(c) |> ignore

    sb.ToString()

let private fileHeader = "// <auto-generated/>\nnamespace FSharp.ModelsDev.Catalog.Generated\n"

let generateProviderIndex (providerIds: seq<string>) : string =
    let sb = StringBuilder(fileHeader)
    sb.Append("\nmodule ProviderIndex =\n    let providerIds: string[] = [|\n") |> ignore

    for id in providerIds do
        sb.Append("        \"").Append(escapeString id).Append("\"\n") |> ignore

    sb.Append("    |]\n") |> ignore
    sb.ToString()

let generateModelIndex (modelKeys: seq<string * string>) : string =
    let sb = StringBuilder(fileHeader)
    sb.Append("\nmodule ModelIndex =\n    let modelKeys: (string * string)[] = [|\n") |> ignore

    for providerId, modelId in modelKeys do
        sb
            .Append("        (\"")
            .Append(escapeString providerId)
            .Append("\", \"")
            .Append(escapeString modelId)
            .Append("\")\n")
        |> ignore

    sb.Append("    |]\n") |> ignore
    sb.ToString()
